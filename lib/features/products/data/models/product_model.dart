import 'package:factory_management/features/products/domain/entities/product.dart';

class ProductModel extends Product {
  const ProductModel({
    required super.id,
    required super.name,
    required super.slug,
    required super.sku,
    required super.categoryId,
    required super.categoryName,
    required super.description,
    required super.shortDescription,
    required super.price,
    required super.discountPrice,
    required super.stockQuantity,
    required super.minimumStock,
    required super.unit,
    required super.dimensions,
    required super.thickness,
    required super.finish,
    required super.color,
    required super.originCountry,
    required super.materialType,
    required super.weight,
    super.waterAbsorption,
    super.hardness,
    super.application,
    super.edgeType,
    required super.featured,
    required super.active,
    required super.images,
    required super.createdAt,
    required super.updatedAt,
    super.createdBy,
    super.lastUpdatedBy,
    super.isDeleted = false,
    super.deletedAt,
    super.variantIds,
    super.parentProductId,
  });

  factory ProductModel.fromJson(Map<String, dynamic> json) {
    return ProductModel(
      id: json['id'] as String,
      name: json['name'] as String,
      slug: json['slug'] as String,
      sku: json['sku'] as String,
      categoryId: json['categoryId'] as String,
      categoryName: json['categoryName'] as String,
      description: json['description'] as String,
      shortDescription: json['shortDescription'] as String,
      price: (json['price'] as num).toDouble(),
      discountPrice: (json['discountPrice'] as num).toDouble(),
      stockQuantity: json['stockQuantity'] as int,
      minimumStock: json['minimumStock'] as int,
      unit: json['unit'] as String,
      dimensions: json['dimensions'] as String,
      thickness: json['thickness'] as String,
      finish: json['finish'] as String,
      color: json['color'] as String,
      originCountry: json['originCountry'] as String,
      materialType: json['materialType'] as String,
      weight: (json['weight'] as num).toDouble(),
      waterAbsorption: json['waterAbsorption'] as String?,
      hardness: json['hardness'] as String?,
      application: json['application'] as String?,
      edgeType: json['edgeType'] as String?,
      featured: json['featured'] as bool,
      active: json['active'] as bool,
      images: List<String>.from(json['images'] as List),
      createdAt: DateTime.parse(json['createdAt'] as String),
      updatedAt: DateTime.parse(json['updatedAt'] as String),
      createdBy: json['createdBy'] as String?,
      lastUpdatedBy: json['lastUpdatedBy'] as String?,
      isDeleted: json['isDeleted'] as bool? ?? false,
      deletedAt: json['deletedAt'] != null ? DateTime.parse(json['deletedAt'] as String) : null,
      variantIds: json['variantIds'] != null ? List<String>.from(json['variantIds'] as List) : null,
      parentProductId: json['parentProductId'] as String?,
    );
  }

  Map<String, dynamic> toJson() {
    return {
      'id': id,
      'name': name,
      'slug': slug,
      'sku': sku,
      'categoryId': categoryId,
      'categoryName': categoryName,
      'description': description,
      'shortDescription': shortDescription,
      'price': price,
      'discountPrice': discountPrice,
      'stockQuantity': stockQuantity,
      'minimumStock': minimumStock,
      'unit': unit,
      'dimensions': dimensions,
      'thickness': thickness,
      'finish': finish,
      'color': color,
      'originCountry': originCountry,
      'materialType': materialType,
      'weight': weight,
      'waterAbsorption': waterAbsorption,
      'hardness': hardness,
      'application': application,
      'edgeType': edgeType,
      'featured': featured,
      'active': active,
      'images': images,
      'createdAt': createdAt.toIso8601String(),
      'updatedAt': updatedAt.toIso8601String(),
      'createdBy': createdBy,
      'lastUpdatedBy': lastUpdatedBy,
      'isDeleted': isDeleted,
      'deletedAt': deletedAt?.toIso8601String(),
      'variantIds': variantIds,
      'parentProductId': parentProductId,
    };
  }

  factory ProductModel.fromEntity(Product product) {
    return ProductModel(
      id: product.id,
      name: product.name,
      slug: product.slug,
      sku: product.sku,
      categoryId: product.categoryId,
      categoryName: product.categoryName,
      description: product.description,
      shortDescription: product.shortDescription,
      price: product.price,
      discountPrice: product.discountPrice,
      stockQuantity: product.stockQuantity,
      minimumStock: product.minimumStock,
      unit: product.unit,
      dimensions: product.dimensions,
      thickness: product.thickness,
      finish: product.finish,
      color: product.color,
      originCountry: product.originCountry,
      materialType: product.materialType,
      weight: product.weight,
      waterAbsorption: product.waterAbsorption,
      hardness: product.hardness,
      application: product.application,
      edgeType: product.edgeType,
      featured: product.featured,
      active: product.active,
      images: product.images,
      createdAt: product.createdAt,
      updatedAt: product.updatedAt,
      createdBy: product.createdBy,
      lastUpdatedBy: product.lastUpdatedBy,
      isDeleted: product.isDeleted,
      deletedAt: product.deletedAt,
      variantIds: product.variantIds,
      parentProductId: product.parentProductId,
    );
  }
}
